"""Generate the dbt star-schema, mart and reconciliation models from the governed Phase 4 T-SQL.

The governed scripts (sql/schema/03, 04, sql/transformations/07, 08, sql/validation/09, 11,
sql/analysis/10) stay the source of truth. This script translates them with the same T-SQL to
DuckDB translation the governed DuckDB build uses (src.sql_model.engines.DuckDBEngine.translate)
and rewrites each statement as a dbt model:

  INSERT INTO dw.x (...) VALUES / SELECT ...   ->  model x: the inserts as one UNION ALL, cast to
                                                    the column types of the CREATE TABLE in 03/04
  CREATE VIEW mart.v / recon.v                  ->  view model v
  SELECT ... INTO recon.t (CREATE TABLE AS)     ->  table model t
  stg.t / dw.t / mart.t / recon.t references    ->  {{ ref() }}

Batches marked @tsql-only (columnstore maintenance, THROW) are skipped, exactly as in the governed
DuckDB build; the dbt tests take the place of the THROW checks.

Run from the project root with the project environment:
    python dbt/scripts/generate_governed_models.py          (writes the models)
    python dbt/scripts/generate_governed_models.py --check  (exit 1 if a model is out of date)
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

import sqlglot  # noqa: E402
from sqlglot import exp  # noqa: E402

from src.sql_model.engines import DuckDBEngine  # noqa: E402
from src.sql_model.scripts import split_batches  # noqa: E402

MODELS = ROOT / "dbt" / "models"
FOLDER = {"dw": MODELS / "intermediate" / "dw", "mart": MODELS / "marts", "recon": MODELS / "recon"}
DDL = ["sql/schema/03_create_dimension_tables.sql", "sql/schema/04_create_fact_tables.sql",
       "sql/staging/02_create_staging_tables.sql"]
LOADS = ["sql/transformations/07_load_dimensions.sql", "sql/transformations/08_load_facts.sql",
         "sql/validation/09_reconciliation.sql", "sql/analysis/10_analytical_views.sql",
         "sql/validation/11_kpi_validation.sql"]
# recon.expected is loaded by the governed runner from Phase 3 outputs; dbt builds it in
# models/recon/expected.sql (hand-written), so its DDL is not turned into a model here.
HAND_WRITTEN = {("recon", "expected")}


def model_name(schema: str, table: str) -> str:
    return f"stg_{table}" if schema == "stg" else table


def statements(rel: str):
    for batch in split_batches(ROOT / rel):
        if not batch.runs_on("duckdb"):
            continue
        for sql in DuckDBEngine.translate(batch.text):
            yield batch, sqlglot.parse_one(sql, read="duckdb")


def table_id(t: exp.Table) -> tuple[str, str]:
    return t.db.lower(), t.name.lower()


def with_refs(node: exp.Expression, deps: set, self_tid: tuple | None = None, self_cte: str = "") -> str:
    def swap(n):
        if isinstance(n, exp.Table) and self_tid and table_id(n) == self_tid:
            # an insert that reads its own target (the UNKNOWN-member guard) sees the rows inserted before it
            new = exp.Table(this=exp.to_identifier(self_cte))
            if n.alias:
                new.set("alias", n.args.get("alias"))
            return new
        if isinstance(n, exp.Table) and n.db and n.db.lower() in ("stg", "dw", "mart", "recon"):
            m = model_name(*table_id(n))
            deps.add(m)
            new = exp.Table(this=exp.to_identifier(f"__REF_{m}__"))
            if n.alias:
                new.set("alias", n.args.get("alias"))
            return new
        return n
    sql = node.transform(swap).sql(dialect="duckdb", pretty=True)
    return re.sub(r"__REF_(\w+?)__", lambda m: "{{ ref('" + m.group(1) + "') }}", sql)


def header(sources: list[str], kind: str, extra: str = "") -> str:
    lines = ["-- Generated by dbt/scripts/generate_governed_models.py from the governed T-SQL; do not edit by hand.",
             f"-- Source: {', '.join(sorted(set(sources)))}"]
    if extra:
        lines.append(f"-- {extra}")
    return "\n".join(lines) + "\n" + "{{ config(materialized='" + kind + "') }}\n\n"


def build() -> dict[Path, str]:
    columns: dict[tuple, list] = {}
    for rel in DDL + ["sql/analysis/10_analytical_views.sql"]:
        for _, st in statements(rel):
            if isinstance(st, exp.Create) and st.kind == "TABLE" and isinstance(st.this, exp.Schema):
                tid = table_id(st.this.this)
                columns[tid] = [(c.name, c.args["kind"].sql(dialect="duckdb"))
                                for c in st.this.expressions if isinstance(c, exp.ColumnDef)]

    inserts: dict[tuple, list] = {}
    out: dict[Path, str] = {}
    described: dict[tuple, tuple] = {}     # (schema, name) -> (materialisation, source scripts)
    order = []
    for rel in LOADS:
        for batch, st in statements(rel):
            if isinstance(st, exp.Insert):
                tid = table_id(st.this.this)
                cols = [c.name for c in st.this.expressions]
                inserts.setdefault(tid, []).append((rel, cols, st.expression))
                if tid not in order:
                    order.append(tid)
            elif isinstance(st, exp.Create) and st.kind in ("VIEW", "TABLE") and st.expression is not None:
                tid = table_id(st.this if isinstance(st.this, exp.Table) else st.this.this)
                deps: set = set()
                body = with_refs(st.expression, deps)
                kind = "view" if st.kind == "VIEW" else "table"
                out[FOLDER[tid[0]] / f"{tid[1]}.sql"] = header([rel], kind) + body + "\n"
                described[tid] = (kind, [rel])
            elif isinstance(st, (exp.Drop, exp.Delete, exp.TruncateTable)) or \
                    (isinstance(st, exp.Create) and st.expression is None):
                continue      # DDL and re-run housekeeping: dbt rebuilds every relation
            else:
                raise SystemExit(f"{rel} batch {batch.index}: unhandled statement {type(st).__name__}")

    for tid in order:
        if tid in HAND_WRITTEN:
            continue
        cols = columns[tid]
        ctes, rels, deps = [], [], set()
        for k, (rel, ins_cols, expr) in enumerate(inserts[tid], start=1):
            rels.append(rel)
            alias = ", ".join(ins_cols)
            if isinstance(expr, exp.Values):
                part = f"SELECT * FROM (SELECT * FROM ({expr.sql(dialect='duckdb')})) AS v({alias})"
            else:
                part = f"SELECT * FROM (\n{with_refs(expr, deps, tid, f'loaded_{k - 1}')}\n) AS s({alias})"
            ctes.append(f"insert_{k} AS (\n{part}\n)")
            prior = f"SELECT * FROM loaded_{k - 1} UNION ALL BY NAME " if k > 1 else ""
            ctes.append(f"loaded_{k} AS (\n{prior}SELECT * FROM insert_{k}\n)")
        missing = [c for c, _ in cols if not all(c in ic for _, ic, _ in inserts[tid])]
        if missing:
            raise SystemExit(f"{tid}: columns not loaded by every insert: {missing}")
        select = ",\n       ".join(f"CAST({c} AS {t}) AS {c}" for c, t in cols)
        body = ("WITH " + ",\n".join(ctes) + f"\nSELECT {select}\nFROM loaded_{len(inserts[tid])}\n")
        out[FOLDER[tid[0]] / f"{tid[1]}.sql"] = header(
            rels, "table", f"Column types from the governed CREATE TABLE {tid[0]}.{tid[1]}.") + body
        described[tid] = ("table", rels)

    for schema, folder in FOLDER.items():
        lines = ["version: 2", "", "# Generated by dbt/scripts/generate_governed_models.py; do not edit by hand.", "models:"]
        for (s, name), (kind, rels) in sorted(described.items()):
            if s == schema:
                lines += [f"  - name: {name}",
                          f"    description: \"Governed {s}.{name} ({kind}), ported unchanged from "
                          f"{', '.join(sorted(set(rels)))}.\""]
        out[folder / "_governed_models.yml"] = "\n".join(lines) + "\n"
    return out


def main() -> int:
    check = "--check" in sys.argv
    models = build()
    stale = []
    for path, text in sorted(models.items()):
        if check:
            if not path.exists() or path.read_bytes().decode("utf-8") != text:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(text.encode("utf-8"))
    if check:
        print("\n".join(stale) if stale else f"{len(models)} generated files up to date")
        return 1 if stale else 0
    print(f"wrote {len(models)} files")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
