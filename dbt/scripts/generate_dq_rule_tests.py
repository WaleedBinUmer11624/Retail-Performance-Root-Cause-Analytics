def quoted(s: str) -> str:
    """A YAML double-quoted scalar."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build() -> dict[Path, str]:
    """The text of each generated properties file, keyed by its path."""
    with open(RESULTS, encoding="utf-8") as fh:
        results = {r["rule_id"]: r for r in csv.DictReader(fh)}
    by_model = {m: [] for m in DESCRIPTIONS}
    for rule, (model, test, args) in SPEC.items():
        by_model[model].append((rule, test, args))
    blocks = {folder: [] for folder in FOLDERS}
    for model, rules in by_model.items():
        lines = [f"  - name: {model}", f"    description: {quoted(DESCRIPTIONS[model])}"]
        if rules:
            lines.append("    data_tests:")
        for rule, test, args in sorted(rules):
            r = results[rule]
            lines += [f"      - {test}:", f"          name: dq_{rule.replace('-', '_')}",
                      f"          description: {quoted(rule + ': ' + r['check'])}", "          arguments:",
                      f"            rule_id: {rule}", f"            failed: {r['rows_failed']}",
                      f"            checked: {r['rows_checked']}"]
            for k, v in args.items():
                lines.append(f"            {k}: [{', '.join(v)}]" if isinstance(v, list) else f"            {k}: {quoted(v)}")
            lines += ["          config:", f"            tags: [dq, {rule}]", f"            meta: {{rule_id: {rule}}}"]
        blocks["staging/raw" if model.startswith("stg_raw") else "intermediate/dq"].append("\n".join(lines))
    return {MODELS / folder / "_models.yml": HEADER.format(what) + "\n\n".join(blocks[folder]) + "\n"
            for folder, what in FOLDERS.items()}


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, text in build().items():
        if check:
            if not path.exists() or path.read_bytes().decode("utf-8") != text:
                stale.append(path.relative_to(ROOT).as_posix())
        else:
            path.write_bytes(text.encode("utf-8"))
    if check:
        print("\n".join(stale) if stale else f"{len(SPEC)} generic rule tests up to date")
        return 1 if stale else 0
    print(f"wrote {len(SPEC)} generic rule tests")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
