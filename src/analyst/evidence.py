"""The governed evidence layer.

Every number that can reach a user is produced here, from a registered query template or from a
validated Phase 6-10 artifact. Nothing in this module is generated by a language model, and
nothing here recomputes a KPI that a governed view already publishes.

If the evidence for a question is not available, the package is marked insufficient. The analyst
never fills the gap with its own arithmetic.

Inputs: a read-only engine, registered query templates and validated artifacts. Outputs: evidence
records and packages, each value tagged with its source, period, filters and provenance.
"""
from __future__ import annotations

from dataclasses import dataclass, field
from pathlib import Path

import pandas as pd

from .intents import ParsedQuestion
from .sql_guard import execute


class InsufficientEvidence(RuntimeError):
    """The governed sources cannot support an answer. The correct response is to say so."""


@dataclass(frozen=True)
class EvidenceRecord:
    """One governed value and the context needed to cite it."""
    evidence_id: str
    evidence_type: str          # FACT | ATTRIBUTION | ASSOCIATION | INTERPRETATION | LIMITATION
    source: str                 # mart object or artifact path
    metric: str
    value: object
    comparison_value: object | None
    period: str
    filters: dict
    provenance: str
    note: str = ""

    def to_dict(self) -> dict:
        """JSON-ready copy."""
        return {
            "evidence_id": self.evidence_id, "evidence_type": self.evidence_type, "source": self.source,
            "metric": self.metric, "value": self.value, "comparison_value": self.comparison_value,
            "period": self.period, "filters": self.filters, "provenance": self.provenance, "note": self.note,
        }


@dataclass
class EvidencePackage:
    """Everything gathered to answer one question, including what is missing."""
    question: str
    intent: str
    filters: dict
    period: str
    interpretation: str
    headline: dict
    drivers: list[dict] = field(default_factory=list)
    supporting_metrics: list[dict] = field(default_factory=list)
    records: list[EvidenceRecord] = field(default_factory=list)
    sources: list[str] = field(default_factory=list)
    limitations: list[str] = field(default_factory=list)
    sufficient: bool = True

    def add(self, record: EvidenceRecord) -> EvidenceRecord:
        """Append a record and register its source once."""
        self.records.append(record)
        if record.source not in self.sources:
            self.sources.append(record.source)
        return record

    def numeric_values(self) -> set[float]:
        """Every number in the package; an answer may only quote values from this set."""
        values: set[float] = set()
        # bool is excluded throughout: True would otherwise be admitted as the number 1.
        for record in self.records:
            for value in (record.value, record.comparison_value):
                if isinstance(value, (int, float)) and not isinstance(value, bool):
                    values.add(float(value))
        for entry in self.drivers:
            for key in ("amount_eur", "share_pct", "value"):
                if isinstance(entry.get(key), (int, float)) and not isinstance(entry.get(key), bool):
                    values.add(float(entry[key]))
        for entry in self.supporting_metrics:
            if isinstance(entry.get("value"), (int, float)) and not isinstance(entry.get("value"), bool):
                values.add(float(entry["value"]))
        for key in ("actual", "comparison", "change"):
            if isinstance(self.headline.get(key), (int, float)) and not isinstance(self.headline.get(key), bool):
                values.add(float(self.headline[key]))
        return values

    def to_dict(self) -> dict:
        """JSON-ready copy."""
        return {
            "question": self.question, "intent": self.intent, "filters": self.filters, "period": self.period,
            "interpretation": self.interpretation, "headline": self.headline, "drivers": self.drivers,
            "supporting_metrics": self.supporting_metrics,
            "evidence": [record.to_dict() for record in self.records], "sources": self.sources,
            "limitations": self.limitations, "sufficient": self.sufficient,
        }


class AnalystContext:
    """Holds the read-only engine, the governed artifacts and the resolved dimension tables."""

    def __init__(self, root: Path, config: dict, engine=None, artifacts: dict | None = None):
        self.root = root
        self.config = config
        self.engine = engine
        self.artifacts = artifacts or {}
        self._dimensions: dict | None = None
        self._query_log: list[str] = []

    def query(self, template: str, params: dict) -> pd.DataFrame:
        """Run a registered template under the configured policy and log its name."""
        database = self.config["database"]
        frame = execute(self.engine, template, params, database["statement_policy"],
                        set(database["allowed_objects"]), set(database["allowed_dimensions"]))
        self._query_log.append(template)
        return frame

    @property
    def query_log(self) -> list[str]:
        """Copy of the template names run so far."""
        return list(self._query_log)

    @property
    def dimensions(self) -> dict:
        """Stores, categories and suppliers from the warehouse, loaded once and cached."""
        if self._dimensions is None:
            if self.engine is None:
                raise InsufficientEvidence(
                    "The governed dimension tables are not reachable, so entities cannot be verified")
            stores = self.query("store_dimension", {})
            categories = self.query("category_dimension", {})
            suppliers = self.query("supplier_dimension", {})
            self._dimensions = {
                "stores": set(stores["store_id"]),
                "store_names": list(zip(stores["store_id"], stores["store_name"])),
                "categories": list(categories["category"]),
                "suppliers": [name for name in suppliers["supplier_name"] if name != "Unknown supplier"],
            }
        return self._dimensions

    def last_complete_week(self) -> dict:
        """Final entry of the retail week calendar artifact."""
        weeks = self.artifacts["weeks"]
        if not len(weeks):
            raise InsufficientEvidence("No retail week calendar is available")
        return weeks[-1]

    def artifact(self, key: str) -> pd.DataFrame:
        """A loaded, non-empty artifact frame, or InsufficientEvidence."""
        if key not in self.artifacts:
            raise InsufficientEvidence(f"The validated artifact '{key}' is not available to the analyst")
        frame = self.artifacts[key]
        if frame is None or not len(frame):
            raise InsufficientEvidence(f"The validated artifact '{key}' is empty")
        return frame

    def path(self, key: str) -> Path:
        """Absolute path of a configured artifact; Phase 6 keys are checked first."""
        return self.root / self.config["evidence_artifacts"]["phase6"][key] \
            if key in self.config["evidence_artifacts"]["phase6"] \
            else self.root / self._artifact_path(key)

    def _artifact_path(self, key: str) -> str:
        for phase in self.config["evidence_artifacts"].values():
            if key in phase:
                return phase[key]
        raise InsufficientEvidence(f"No configured artifact for '{key}'")
